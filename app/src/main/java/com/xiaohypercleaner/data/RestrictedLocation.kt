package com.xiaohypercleaner.data

/**
 * Местоположение кнопки разблокировки Restricted Settings на экране App Info.
 * Используется в PermissionFlowManager для показа умных подсказок:
 *  - TOP_MENU: кнопка в правом верхнем меню (⋮ → «Разрешить»)
 *  - BOTTOM_LIST: кнопка внизу списка настроек
 *  - UNKNOWN: местоположение неизвестно, показываем общую подсказку
 *  - ABSENT: кнопка отсутствует (не требуется разблокировка)
 *
 * ИСПРАВЛЕНО: восстановлены корректные закрытия KDoc-комментариев.
 */
enum class RestrictedLocation {

    /** Местоположение неизвестно — показываем общую карточку */
    UNKNOWN,

    /** Кнопка в правом верхнем меню (⋮) */
    TOP_MENU,

    /** Кнопка внизу списка настроек */
    BOTTOM_LIST,

    /** Кнопка отсутствует — разблокировка не требуется */
    ABSENT
}