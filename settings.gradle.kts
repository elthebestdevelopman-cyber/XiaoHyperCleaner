// ───────────────────────────────────────────────────────────────
// Репозитории для поиска Gradle-плагинов
// ───────────────────────────────────────────────────────────────
pluginManagement {
    repositories {
        google()             // AGP (Android Gradle Plugin)
        mavenCentral()       // Kotlin, Compose plugins
        gradlePluginPortal() // Прочие плагины (включая foojay-resolver)
    }
}

// ───────────────────────────────────────────────────────────────
// Автоматическая загрузка JDK (Foojay Toolchains Resolver)
// ───────────────────────────────────────────────────────────────
// Позволяет Gradle автоматически скачать нужный JDK (например, Java 17),
// если он не установлен на машине сборки.
//
// ВНИМАНИЕ: проверь, что версия 1.0.0 существует на момент сборки.
// Актуальные версии: 0.8.0, 0.9.0 (на 2024 год).
// Если сборка падает с ошибкой "plugin not found" — смени на 0.9.0.
plugins {
    id("org.gradle.toolchains.foojay-resolver-convention") version "1.0.0"
}

// ───────────────────────────────────────────────────────────────
// Управление разрешением зависимостей
// ───────────────────────────────────────────────────────────────
dependencyResolutionManagement {
    // ИСПРАВЛЕНО: запрещаем модулям переопределять репозитории.
    // Это предотвращает случайные проблемы с разрешением зависимостей,
    // когда разные модули используют разные репозитории.
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)

    repositories {
        google()        // AndroidX, Jetpack Compose, Material
        mavenCentral()  // Kotlinx Coroutines, Mockito, Shizuku API, Robolectric
    }
}

// ───────────────────────────────────────────────────────────────
// Структура проекта
// ───────────────────────────────────────────────────────────────
rootProject.name = "XiaoHyperCleaner"
include(":app")